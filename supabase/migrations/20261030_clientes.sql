-- Ejecutar una sola vez en Supabase > SQL Editor.

CREATE TABLE IF NOT EXISTS public.clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  telefono text NOT NULL UNIQUE,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.clientes TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.clientes_id_seq TO authenticated;

DROP POLICY IF EXISTS clientes_admin_all ON public.clientes;
CREATE POLICY clientes_admin_all
ON public.clientes
FOR ALL
TO authenticated
USING (auth.uid() = '32824edd-cce8-4c9e-b61f-d7b31e60bc62'::uuid)
WITH CHECK (auth.uid() = '32824edd-cce8-4c9e-b61f-d7b31e60bc62'::uuid);

-- Importa automáticamente los clientes que ya aparecen en las citas.
-- Se conserva un solo registro por teléfono y se prioriza el nombre de la cita más reciente.
INSERT INTO public.clientes (nombre, telefono)
SELECT DISTINCT ON (telefono_limpio)
  btrim(c.cliente),
  telefono_limpio
FROM (
  SELECT
    cliente,
    regexp_replace(coalesce(telefono, ''), '[^0-9]', '', 'g') AS telefono_limpio,
    creado_en,
    id
  FROM public.citas
) AS c
WHERE btrim(coalesce(c.cliente, '')) <> ''
  AND length(c.telefono_limpio) >= 7
ORDER BY telefono_limpio, creado_en DESC NULLS LAST, id DESC
ON CONFLICT (telefono) DO UPDATE
SET nombre = EXCLUDED.nombre,
    actualizado_en = now();
